import { AppSettings } from '../types';

export type SupportedLanguage = 'en' | 'de' | 'it' | 'es' | 'fr';

export function getDeviceLanguage(): SupportedLanguage {
  if (typeof navigator === 'undefined' || !navigator.language) {
    return 'en';
  }
  const lang = navigator.language.toLowerCase();
  if (lang.startsWith('de')) return 'de';
  if (lang.startsWith('it')) return 'it';
  if (lang.startsWith('es')) return 'es';
  if (lang.startsWith('fr')) return 'fr';
  return 'en';
}

export function getCurrentLanguage(settingsLanguage?: string): SupportedLanguage {
  if (!settingsLanguage || settingsLanguage === 'auto') {
    return getDeviceLanguage();
  }
  return (settingsLanguage as SupportedLanguage) || 'en';
}

